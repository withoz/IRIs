// IRIS — Enscape 값이 없을 때 거칠기·금속성을 추측한다 (11번 (g))
//
// 왜 필요한가
//   SketchUp 은 PBR 파라미터를 주지 않습니다. Enscape 로 손댄 재질만
//   `Enscape.Material/MaterialData` 를 답니다. 골프존 모델은 135개 중
//   **26개뿐**이고 나머지 109개는 `roughness 0.5 · metalness 0` 고정이었습니다.
//
//   0.5 는 재고 정한 값이 아닙니다. 실측하면 **틀린 쪽으로 치우쳐 있습니다.**
//
// 기본값 0.9 는 어디서 왔나 — **측정**
//   같은 모델에서 Enscape 값이 있는 재질 27벌의 거칠기를 세어 보면
//   (out/sketchup/rough_probe.txt, [5]절):
//
//       0.90  ########## 10개      중앙값 0.82 · 평균 0.70
//       0.00  ##  2 · 0.50 ## 2 · 0.60 ## 2 · 1.00 ## 2 · 나머지 각 1개
//
//   0.90 에 몰린 10개는 잔디·돌·검은 라미네이트·전기 레이스웨이처럼
//   **서로 전혀 다른 재질**인데 `R=0.900 M=0.000 S=0.500` 이 한 글자도
//   다르지 않습니다. 저작자가 고른 값이라기엔 이상합니다.
//
//   결정적인 것은 그중 **4개가 SELF_ILLUMINATED** 라는 점입니다. 발광면은
//   거칠기가 화면에 거의 드러나지 않아 일부러 맞출 이유가 없습니다. 그런데도
//   정확히 0.900 입니다. 손대지 않은 값 — 즉 **Enscape 의 기본값**입니다
//   (값 자체는 측정, "기본값이다"는 추론).
//
//   우리 목표가 Enscape 화면에 가까워지는 것이므로, 모르는 재질은 Enscape 가
//   모를 때 쓰는 값으로 두는 것이 맞습니다.
//
// 이름 표는 왜 이렇게 작은가
//   같은 프로브 [4]절이 제 첫 집계를 뒤집었습니다. "영어 낱말이 든 이름
//   57.8%(면 수 79%)" 는 **거짓 신호**였습니다 — 그 대부분이 `pro_02`
//   (63,678면) · `Color M08`(29,472면) · `Material~29` 처럼 뜻이 없는
//   이름입니다. 실제로 뜻이 있는 이름은 `_leather, fawn brown`(24,261면),
//   `Vegetation_Bark_*`(5,805면), `Sketchy_Siding_Scale`(2,352면),
//   `_wood laminate1`, `Natural birch`, `Metal_*`, `stone05` 정도로
//   **면 수의 14.1%** 뿐입니다.
//
//   그래서 이름 표는 큰 몫을 맡지 않습니다. 맡는 곳은 하나뿐입니다 —
//   **기본값 0.9 가 분명히 틀리는 자리**, 즉 0.9 보다 반짝이는 재질.
//   거울·크롬·타일·대리석·가죽·목재가 거기입니다.
//
//   0.9 보다 **거친** 쪽(아스팔트 0.98, 카펫 0.98)은 일부러 넣지 않았습니다.
//   0.05 를 벌자고 오탐 위험을 늘릴 이유가 없습니다.
//
// ⚠ 09번 8-i 를 반복하지 않으려고
//   "큰 면만 유리로 본다"는 규칙은 데이터가 깨끗하게 갈려서 그럴듯했지만
//   램프 렌즈를 깨뜨렸을 것입니다. 그래서 이 표는 셋을 지킵니다.
//
//     1. **애매하면 손대지 않습니다.** `metal`·`steel`·`aluminum` 은 뺐습니다 —
//        건축에서 그 낱말은 도장 판넬일 때가 더 많고, 흰 도장을 금속으로
//        만들면 흰 거울이 됩니다. 되돌릴 수 없는 종류의 실수입니다.
//     2. **사용자가 덮어쓸 수 있습니다** — 재질 편집기 + 저장, 되돌리기 단추.
//     3. **어떤 규칙이 왜 걸렸는지 남깁니다** — GuessResult::rule.

#pragma once

#include <string>
#include <string_view>

namespace iris::bridge
{
    struct SurfaceGuess
    {
        float roughness = 0.9f;
        float metalness = 0.0f;

        // 어떤 규칙이 걸렸는지. 기본값이면 비어 있습니다.
        // 정적 문자열이라 수명 걱정이 없습니다.
        const char* rule = nullptr;
    };

    // `name` 은 SketchUp 재질 이름(UTF-8). `defaultRoughness` 는 아무 규칙도
    // 걸리지 않았을 때 쓸 값입니다. `useNameRules` 가 거짓이면 표를 통째로
    // 건너뛰고 기본값만 돌려줍니다 — A/B 할 때 필요합니다.
    [[nodiscard]] SurfaceGuess GuessSurface(std::string_view name,
                                            float            defaultRoughness,
                                            bool             useNameRules);
}
